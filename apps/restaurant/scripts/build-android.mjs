import { spawnSync } from "node:child_process";
import { log } from "node:console";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { homedir } from "node:os";
import { dirname, join, relative, sep } from "node:path";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";

const app = fileURLToPath(new URL("../", import.meta.url));
const android = join(app, "android");
const buildToolsVersion = "37.0.0";
const gradleVersion = "9.4.1";
const ndkVersion = "27.1.12297006";
const cmakeVersion = "3.22.1";
const windows = process.platform === "win32";
const require = createRequire(import.meta.url);

function run(executable, args, cwd, env) {
  const result = spawnSync(executable, args, { cwd, env, stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(
      `Android build command failed (${result.status ?? result.signal ?? "unknown"}).`,
    );
  }
}

function installedGradle() {
  const userHome = process.env.GRADLE_USER_HOME ?? join(homedir(), ".gradle");
  const versionFolder = `gradle-${gradleVersion}`;
  const wrappers = join(userHome, "wrapper", "dists", `${versionFolder}-bin`);
  const cached = existsSync(wrappers)
    ? readdirSync(wrappers, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => join(wrappers, entry.name, versionFolder))
    : [];
  const launcher = `gradle-gradle-cli-main-${gradleVersion}.jar`;
  const agent = `gradle-instrumentation-agent-${gradleVersion}.jar`;
  const candidates = [process.env.GRADLE_HOME, ...cached];
  const home = candidates.find(
    (candidate) =>
      candidate &&
      existsSync(join(candidate, "lib", launcher)) &&
      existsSync(join(candidate, "lib", "agents", agent)),
  );
  if (!home)
    throw new Error(
      `A local Gradle ${gradleVersion} distribution is required.`,
    );
  return {
    launcher: join(home, "lib", launcher),
    agent: join(home, "lib", "agents", agent),
  };
}

function installedSdk() {
  const localAppData = process.env.LOCALAPPDATA;
  const fallback =
    windows && localAppData
      ? join(localAppData, "Android", "Sdk")
      : join(homedir(), "Android", "Sdk");
  const sdk =
    process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT ?? fallback;
  const platform = join(sdk, "platforms", "android-37.0");
  if (
    !existsSync(join(platform, "android.jar")) ||
    !existsSync(join(platform, "package.xml"))
  ) {
    throw new Error("Install Android SDK Platform 37.0 through SDK Manager.");
  }
  for (const directory of [
    `build-tools/${buildToolsVersion}`,
    `ndk/${ndkVersion}`,
    `cmake/${cmakeVersion}`,
  ]) {
    if (!existsSync(join(sdk, directory, "source.properties"))) {
      throw new Error(`The Android SDK package ${directory} is required.`);
    }
  }
  return sdk;
}

function updateGenerated(relative, find, replacement) {
  const path = join(android, relative);
  const text = readFileSync(path, "utf8");
  if (text.includes(replacement)) return;
  const updated = text.replace(find, () => replacement);
  if (updated === text)
    throw new Error(`The bundled Expo template changed at ${relative}.`);
  writeFileSync(path, updated);
}

const sdk = installedSdk();
const gradle = installedGradle();
const marker = join(android, ".be-fast-generated");
if (existsSync(android) && !existsSync(marker)) {
  throw new Error(
    "The existing android directory was not generated by build:android.",
  );
}

const buildEnv = {
  ...process.env,
  ANDROID_HOME: sdk,
  EXPO_NO_DOTENV: "1",
  EXPO_NO_TELEMETRY: "1",
  EXPO_OFFLINE: "1",
  EXPO_NO_GIT_STATUS: "1",
};
const expo = dirname(require.resolve("expo/package.json"));
try {
  run(
    process.execPath,
    [
      join(expo, "bin", "cli"),
      "prebuild",
      "--platform",
      "android",
      "--no-install",
      "--template",
      join(expo, "template.tgz"),
      "--skip-dependency-update",
      "expo,expo-status-bar,react,react-native",
    ],
    app,
    buildEnv,
  );
} finally {
  if (existsSync(android))
    writeFileSync(marker, "Generated by build:android.\n");
}

// Bundle JavaScript into the debug APK as well as keeping its local network support.
updateGenerated(
  "app/build.gradle",
  "react {",
  "react {\n    debuggableVariants = []",
);

if (windows) {
  const reactNativeRequire = createRequire(
    require.resolve("react-native/package.json"),
  );
  const compilerPackage = dirname(
    reactNativeRequire.resolve("hermes-compiler/package.json"),
  );
  const compiler = join(compilerPackage, "hermesc", "win64-bin", "hermesc.exe");
  const compilerCommand = relative(app, compiler).split(sep).join("/");
  // React Native launches Hermes through cmd from the app root on Windows.
  updateGenerated(
    "app/build.gradle",
    /^[ \t]+hermesCommand = .+$/m,
    `    hermesCommand = ${JSON.stringify(compilerCommand)}`,
  );

  // Keep the Prefab inputs and CMake objects within Ninja's Windows path limit.
  const expoPlugin = 'apply plugin: "expo-root-project"';
  updateGenerated(
    "build.gradle",
    expoPlugin,
    `allprojects { androidProject ->
    androidProject.pluginManager.withPlugin("com.android.base") {
        androidProject.extensions.getByName("androidComponents").finalizeDsl { androidDsl ->
            def cmake = androidDsl.externalNativeBuild.cmake
            if (cmake.path != null) {
                cmake.buildStagingDirectory = rootProject.file("../.android-gradle/cxx/" + androidProject.name)
            }
        }
    }
}

${expoPlugin}`,
  );

  // React Native sets the app's CMake path later, and its codegen targets need a shorter path.
  updateGenerated(
    "app/build.gradle",
    "android {",
    `android {
    externalNativeBuild {
        cmake {
            buildStagingDirectory rootProject.file("../../../.expo/cxx/restaurant")
        }
    }`,
  );
}

const java = process.env.JAVA_HOME
  ? join(process.env.JAVA_HOME, "bin", windows ? "java.exe" : "java")
  : "java";
run(
  java,
  [
    `-javaagent:${gradle.agent}`,
    "-jar",
    gradle.launcher,
    "--gradle-user-home",
    join(app, ".android-gradle"),
    "--no-daemon",
    "--console=plain",
    "-Pandroid.builder.sdkDownload=false",
    "-Pexpo.android.cmakeObjectPathMax=240",
    ":app:assembleDebug",
  ],
  android,
  buildEnv,
);

const apk = join(
  android,
  "app",
  "build",
  "outputs",
  "apk",
  "debug",
  "app-debug.apk",
);
if (!existsSync(apk))
  throw new Error("Gradle completed without generating the expected APK.");
log(`APK: ${apk}`);
