const damascusClock = new Intl.DateTimeFormat("en-US", {
  timeZone: "Asia/Damascus",
  calendar: "gregory",
  numberingSystem: "latn",
  day: "numeric",
  month: "numeric",
  year: "numeric",
  hour: "numeric",
  minute: "2-digit",
  hour12: true,
});

export function formatAdminDateTime(value: string): string {
  const parts = new Map(
    damascusClock
      .formatToParts(new Date(value))
      .map(({ type, value }) => [type, value]),
  );
  const time = `${parts.get("hour")}:${parts.get("minute")} ${parts.get("dayPeriod") === "AM" ? "ص" : "م"}`;
  return `${parts.get("day")} ${months[Number(parts.get("month")) - 1]} ${parts.get("year")}، ${time}`;
}

export function formatAdminCalendarDate(value: string): string {
  const [year, month, day] = value.split("-");
  return `${Number(day)} ${months[Number(month) - 1]} ${year}`;
}

const percentage = new Intl.NumberFormat("en-US", {
  style: "percent",
  maximumFractionDigits: 2,
});

export function formatAdminRate(bps: number): string {
  return percentage.format(bps / 10_000);
}
